/**
 * The catalog held against the CSS: every class it names exists, and every variant of a covered component is in the catalog
 * or in its exclude list with a reason. Answers what is wrong.
 * @return list<string>
 */
function BUILD__CatalogCheck(): array
{
	$catalog = BUILD__Catalog();
	$classes = TOOL__Classes();
	$named = [];
	$wrong = [];
	foreach ($catalog['elements'] as $element) {
		foreach ($element['props'] as $prop) {
			if (isset($prop['attr'])) {
				continue;
			}
			foreach ($prop['family'] as $value) {
				if ($value === '') {
					continue;
				}
				if (isset($prop['compose'])) {
					$other = array_values(array_filter($element['props'], fn(array $one): bool => ($one['compose'] ?? '') === $prop['compose'] && $one['key'] !== $prop['key']))[0] ?? null;
					foreach ($other['family'] ?? [''] as $with) {
						$pair = $prop['key'] === 'tone' ? ['style' => $with, 'tone' => $value] : ['style' => $value, 'tone' => $with];
						if (in_array($pair['style'], ['text', 'link'], true)) {
							$pair['tone'] = '';
						}
						if ($pair['tone'] !== '' || in_array($pair['style'], ['text', 'link'], true)) {
							$name = str_replace(['{style}', '{tone}'], [$pair['style'], $pair['tone']], $prop['compose']);
							$named[$name] = true;
							if (!isset($classes[$name])) {
								$wrong[] = 'tools/catalog.json composes the class ' . $name . ', which no stylesheet has';
							}
						}
					}
					continue;
				}
				$named[$value] = true;
				if (!isset($classes[$value])) {
					$wrong[] = 'tools/catalog.json names the class ' . $value . ', which no stylesheet has';
				}
			}
		}
	}
	$flat = (string)file_get_contents(BUILD_ROOT . '/editor/flat.js');
	foreach ($catalog['write']['kinds'] as $kind) {
		if (preg_match('~^\t' . preg_quote($kind, '~') . ': \(~m', $flat) !== 1) {
			$wrong[] = 'tools/catalog.json lets an AI answer the kind ' . $kind . ', which editor/flat.js does not write';
		}
	}
	foreach ($catalog['covers'] as $component) {
		preg_match_all('~\.(' . preg_quote(explode('-', $component)[0], '~') . '-[a-z0-9-]+)~', (string)file_get_contents(BUILD_ROOT . '/css/components/' . $component . '.css'), $found);
		foreach (array_unique($found[1]) as $name) {
			if ($name !== $component && !isset($named[$name]) && !isset($catalog['exclude'][$component][$name])) {
				$wrong[] = 'css/components/' . $component . '.css has the variant ' . $name . ', which tools/catalog.json neither covers nor excludes';
			}
		}
	}
	return $wrong;
}

/**
 * Each file a project serves: [its bytes gzip -9, the budget].
 * @return array<string, array{int, int}>
 */
function BUILD__Budgets(): array
{
	$sizes = [];
	foreach (BUILD_BUDGETS as $files => $budget) {
		$sizes[$files] = [array_sum(array_map(fn(string $file): int => strlen((string)gzencode((string)file_get_contents($file), 9)), glob(BUILD_ROOT . '/' . $files) ?: [])), $budget];
	}
	return $sizes;
}

/**
 * Writes the generated files, or with --check only compares them, then holds the budgets; the exit code.
 * @param list<string> $argv
 */
function BUILD__Main(array $argv): int
{
	$check = in_array('--check', $argv, true);
	$vocab = BUILD__Vocabulary();
	$wrong = [...BUILD__TextsCheck($vocab), ...BUILD__CommandsCheck(), ...BUILD__SamplesCheck(), ...BUILD__MotionCheck(), ...BUILD__CatalogCheck(), ...BUILD__ToolsCalls(), ...array_map(fn(string $failure): string => 'tools/min.php  ' . $failure, MIN__SelfTest())];
	if ($wrong !== []) {
		fwrite(STDERR, implode("\n", $wrong) . "\n");
		return 1;
	}
	$packages = [];
	foreach (array_keys(BUILD_PACKAGE_SOURCES) as $dist) {
		$packages['dist/' . $dist] = fn(): string => BUILD__Package($dist);
	}
	$tools = [];
	foreach (BUILD_TOOLS_SOURCES as $file => $source) {
		$tools['tools/dist/' . $file] = fn(): string => (string)file_get_contents(BUILD_ROOT . '/' . $source);
	}
	$tools[BUILD_TOOLS_PASSPORT] = fn(): string => BUILD__ToolsPassport();
	$files = ['css/scales.css' => fn(): string => BUILD__ScalesCss($vocab), 'css/utilities.css' => fn(): string => BUILD__UtilitiesCss($vocab), 'editor/catalog.js' => fn(): string => BUILD__CatalogJs(), BUILD_ICONS['css'] => fn(): string => BUILD__IconsCss(), 'dist/' . BUILD_MAIN['css'] => fn(): string => BUILD__Dist('css'), 'dist/' . BUILD_MAIN['js'] => fn(): string => BUILD__Dist('js'), ...$packages, 'dist/' . BUILD_MAIN['floor'] => fn(): string => BUILD__FloorJs(), 'dist/LICENSE' => fn(): string => (string)file_get_contents(BUILD_ROOT . '/LICENSE'), 'dist/LICENSE-editor' => fn(): string => (string)file_get_contents(BUILD_ROOT . '/editor/LICENSE'), 'dist/NOTICE' => fn(): string => (string)file_get_contents(BUILD_ROOT . '/NOTICE'), BUILD_PASSPORT => fn(): string => BUILD__Passport(), BUILD_ICONS_PASSPORT => fn(): string => BUILD__IconsPassport(), ...$tools];
	$stale = [];
	foreach ($files as $file => $made) {
		$text = $made();
		$path = BUILD_ROOT . '/' . $file;
		if (is_file($path) && file_get_contents($path) === $text) {
			continue;
		}
		if ($check) {
			$stale[] = $file;
			continue;
		}
		if (!is_dir(dirname($path))) {
			mkdir(dirname($path), 0777, true);
		}
		file_put_contents($path, $text);
		echo 'wrote ', $file, "\n";
	}
	if ($stale !== []) {
		fwrite(STDERR, 'out of date: ' . implode(', ', $stale) . " - run php tools/build.php\n");
		return 1;
	}
	$changed = BUILD__IconsChanged();
	if ($changed !== '') {
		fwrite(STDERR, $changed . "\n");
		return 1;
	}
	foreach (glob(BUILD_ROOT . '/skills/*/SKILL.md') ?: [] as $skill) {
		if (preg_match('~^\s+version: "' . preg_quote(BUILD__Version(), '~') . '"$~m', (string)file_get_contents($skill)) !== 1) {
			fwrite(STDERR, substr($skill, strlen(BUILD_ROOT) + 1) . ': metadata.version is not the changelog\'s ' . BUILD__Version() . "\n");
			return 1;
		}
	}
	$over = [];
	$line = [];
	foreach (BUILD__Budgets() as $entry => [$size, $budget]) {
		$line[] = sprintf('%s %.1f of %d KB gz', $entry, $size / 1024, $budget / 1024);
		if ($size > $budget) {
			$over[] = $entry;
		}
	}
	echo 'budgets · ', implode(' · ', $line), $over === [] ? '' : ' · OVER: ' . implode(', ', $over), "\n";
	return $over === [] ? 0 : 1;
}

exit(BUILD__Main($argv));
