/** The vocabulary of tools/vocabulary.json, its keys checked; lists stay arrays, maps stay objects. */
function BUILD__Vocabulary(): stdClass
{
	$vocab = json_decode((string)file_get_contents(__DIR__ . '/vocabulary.json'), false, 512, JSON_THROW_ON_ERROR);
	foreach (['region', 'breakpoints', 'tones', 'texts', 'scales', 'utilities'] as $key) {
		if (!isset($vocab->$key)) {
			throw new RuntimeException('tools/vocabulary.json has no "' . $key . '"');
		}
	}
	return $vocab;
}

/** A length of $px pixels in rem, 0 as 0. */
function BUILD__Rem(int $px): string
{
	if ($px === 0) {
		return '0';
	}
	return rtrim(rtrim(sprintf('%.4f', $px / 16), '0'), '.') . 'rem';
}

/** The selector of the class $class: a colon and a dot escaped, a leading digit escaped by its code point. */
function BUILD__Selector(string $class): string
{
	$name = str_replace([':', '.'], ['\\:', '\\.'], $class);
	return '.' . (ctype_digit($name[0]) ? '\\3' . $name[0] . ' ' . substr($name, 1) : $name);
}

/**
 * The rules of one utility entry, class => declarations.
 * @return array<string, string>
 */
function BUILD__UtilityRules(stdClass $entry, stdClass $vocab): array
{
	if (isset($entry->css)) {
		return [$entry->name => $entry->css];
	}
	$rules = [];
	$property = $entry->property;
	$declare = fn(string $value): string => (isset($entry->vendor) ? $entry->vendor . $property . ': ' . $value . '; ' : '') . $property . ': ' . $value;
	foreach (is_array($entry->values ?? null) ? $entry->values : [] as $value) {
		$rules[$entry->name . '-' . $value] = $declare($value);
	}
	foreach (is_object($entry->values ?? null) ? get_object_vars($entry->values) : [] as $key => $value) {
		$rules[$entry->name . '-' . $key] = $declare($value);
	}
	foreach (isset($entry->scale) ? $vocab->scales->{$entry->scale} : [] as $n) {
		$rules[$entry->name . '-' . $n] = $declare('var(--redz-' . $entry->scale . '-' . $n . ')');
	}
	for ($n = 1; $n <= ($entry->count ?? 0); $n++) {
		$rules[$entry->name . '-' . $n] = $declare(str_replace('{n}', (string)$n, $entry->pattern));
	}
	foreach ($entry->px ?? [] as $px) {
		$rules[$entry->name . '-' . $px] = $declare(str_replace('{v}', BUILD__Rem($px), $entry->pattern));
	}
	foreach (isset($entry->tones) ? $vocab->tones : [] as $tone) {
		$rules[$entry->name . '-' . $tone . ($entry->suffix ?? '')] = $declare(str_replace('{tone}', $tone, $entry->tones));
	}
	return $rules;
}

/** The scale tokens of the vocabulary on :root. */
function BUILD__ScalesCss(stdClass $vocab): string
{
	$out = BUILD_HEAD . "\n@layer tokens {\n\t:root {\n";
	foreach (get_object_vars($vocab->scales) as $scale => $values) {
		foreach ($values as $n) {
			$out .= "\t\t--redz-" . $scale . '-' . $n . ': ' . BUILD__Rem($n) . ";\n";
		}
	}
	return $out . "\t}\n}\n";
}

/** The utilities: the plain rules - an entry's `rtl` is its rule right to left - then the prefixed ones by breakpoint
 *  inside the region's container query, then print. */
function BUILD__UtilitiesCss(stdClass $vocab): string
{
	$plain = [];
	$prefixed = [];
	$printed = [];
	foreach ($vocab->utilities as $entry) {
		foreach (BUILD__UtilityRules($entry, $vocab) as $class => $css) {
			if (isset($plain[$class])) {
				throw new RuntimeException('tools/vocabulary.json makes the class "' . $class . '" twice');
			}
			$plain[$class] = [$entry->selector ?? BUILD__Selector($class), $css];
			if (isset($entry->rtl)) {
				$plain[$class . ':dir(rtl)'] = [BUILD__Selector($class) . ':dir(rtl)', $entry->rtl];
			}
			if ($entry->prefix ?? false) {
				$prefixed[$class] = $css;
			}
			if ($entry->print ?? false) {
				$printed[$class] = $css;
			}
		}
	}
	$out = BUILD_HEAD . "\n@layer utilities {\n";
	foreach ($plain as [$selector, $css]) {
		$out .= "\t" . $selector . ' { ' . $css . "; }\n";
	}
	foreach (get_object_vars($vocab->breakpoints) as $name => $px) {
		$out .= "\n\t@container " . $vocab->region . ' (width >= ' . $px . "px) {\n";
		foreach ($prefixed as $class => $css) {
			$out .= "\t\t" . BUILD__Selector($name . ':' . $class) . ' { ' . $css . "; }\n";
		}
		$out .= "\t}\n";
	}
	$out .= "\n\t@media print {\n";
	foreach ($printed as $class => $css) {
		$out .= "\t\t" . BUILD__Selector('print:' . $class) . ' { ' . $css . "; }\n";
	}
	return $out . "\t}\n}\n";
}

/** One mask rule per icon file, by the file's name, squeezed. */
function BUILD__IconsCss(): string
{
	$out = "@layer base {\n";
	$files = glob(BUILD_ROOT . '/icons/*.svg');
	sort($files, SORT_STRING);
	foreach ($files as $file) {
		$name = basename($file, '.svg');
		if (preg_match('~\A[a-z0-9]+(?:-[a-z0-9]+)*\z~', $name) !== 1) {
			throw new RuntimeException('icons/' . $name . '.svg is not a plain icon name');
		}
		$out .= "\t.bi-" . $name . ' { mask-image: url("../icons/' . $name . ".svg\"); }\n";
	}
	return BUILD_ICONS_HEAD . "\n" . MIN__CssSafe($out . "}\n") . "\n";
}

/** The file's sha256 in the SRI form. */
function BUILD__Hash(string $file): string
{
	return 'sha256-' . base64_encode((string)hash_file('sha256', BUILD_ROOT . '/' . $file, true));
}

/** The pack's passport: its name, the version of Bootstrap Icons it follows, its stylesheet and every file's sha256. */
function BUILD__IconsPassport(): string
{
	$names = [BUILD_ICONS['css'], 'icons/LICENSE', ...array_map(fn(string $file): string => 'icons/' . basename($file), glob(BUILD_ROOT . '/icons/*.svg') ?: [])];
	sort($names, SORT_STRING);
	$lines = array_map(fn(string $file): string => json_encode($file, JSON_UNESCAPED_SLASHES) . ': ' . json_encode(BUILD__Hash($file), JSON_UNESCAPED_SLASHES), $names);
	$encode = fn(mixed $value): string => (string)json_encode($value, JSON_UNESCAPED_SLASHES);
	return "{\n\t\"name\": " . $encode(BUILD_ICONS['name']) . ",\n\t\"version\": " . $encode(BUILD_ICONS['version']) . ",\n\t\"license\": \"MIT\",\n\t\"source\": \"https://github.com/twbs/icons\",\n\t\"css\": " . $encode(BUILD_ICONS['css']) . ",\n\t\"files\": {\n\t\t" . implode(",\n\t\t", $lines) . "\n\t}\n}\n";
}

/** Why the pack differs from what its version's tag published; '' when it does not, or when no such tag is here. */
function BUILD__IconsChanged(): string
{
	$tag = 'icons-' . BUILD_ICONS['version'];
	$proc = proc_open(['git', '-C', BUILD_ROOT, 'show', 'refs/tags/' . $tag . ':' . BUILD_ICONS_PASSPORT], [1 => ['pipe', 'w'], 2 => ['file', '/dev/null', 'w']], $pipes);
	$published = is_resource($proc) ? (string)stream_get_contents($pipes[1]) : '';
	if (is_resource($proc) && proc_close($proc) !== 0) {
		return '';
	}
	$now = BUILD__IconsPassport();
	return $published === '' || $published === $now ? '' : 'the icons differ from the published ' . $tag . ': give the pack a new version in tools/build.php';
}

/**
 * The files the entry $file pulls in, depth first, each once and before the files that pull it in: a stylesheet's
 * `@import url(…)`, a module's `import … from '…'` and `import '…'`.
 * @param array<string, true> $seen
 * @return list<string>
 */
function BUILD__Pulled(string $file, array &$seen = []): array
{
	$seen[$file] = true;
	$pattern = str_ends_with($file, '.css') ? '~^@import url\("([^"]+)"\);~m' : '~^import (?:[^\'"]+ from )?\'([^\']+)\';~m';
	preg_match_all($pattern, (string)file_get_contents(BUILD_ROOT . '/' . $file), $found);
	$files = [];
	foreach ($found[1] as $relative) {
		$pulled = ltrim(str_replace('/./', '/', dirname($file) . '/' . $relative), './');
		do {
			$pulled = (string)preg_replace('~(?<![^/])[\w-]+/\.\./~', '', $pulled, 1, $folded);
		} while ($folded > 0);
		if (!is_file(BUILD_ROOT . '/' . $pulled)) {
			throw new RuntimeException($file . ' pulls in ' . $relative . ', which does not exist');
		}
		if (!isset($seen[$pulled])) {
			array_push($files, ...BUILD__Pulled($pulled, $seen));
		}
	}
	$files[] = $file;
	return $files;
}

/** The version of the changelog's newest released section, `## X.Y.Z - YYYY-MM-DD`. */
function BUILD__Version(): string
{
	if (preg_match('~^## (\d+\.\d+\.\d+) - \d{4}-\d{2}-\d{2}$~mu', (string)file_get_contents(BUILD_ROOT . '/CHANGELOG.md'), $m) !== 1) {
		throw new RuntimeException('CHANGELOG.md has no released section "## X.Y.Z - YYYY-MM-DD"');
	}
	return $m[1];
}

/**
 * The files of dist/ beside its passport, relative to dist/, sorted.
 * @return list<string>
 */
function BUILD__Archived(): array
{
	$files = [];
	foreach (BUILD_ARCHIVED as $pattern) {
		foreach (glob(BUILD_ROOT . '/dist/' . $pattern) ?: [] as $path) {
			if (is_file($path)) {
				$files[] = substr($path, strlen(BUILD_ROOT . '/dist/'));
			}
		}
	}
	sort($files, SORT_STRING);
	return $files;
}

/** The release's stylesheet or script - dist/css/redz-ui.min.css or dist/js/redz-ui.min.js - built and proved by tools/min.php. */
function BUILD__Dist(string $kind): string
{
	$files = $kind === 'css' ? array_slice(BUILD__Pulled('css/index.css'), 0, -1) : BUILD__Pulled('js/index.js');
	return MIN__Bundle(BUILD_ROOT, $files, BUILD_DIST_HEAD)[0];
}

/** A package file of dist/, from its source by tools/min.php: a stylesheet squeezed, a module joined with the modules it
 *  imports - the editor with js/text.js - and given short names. */
function BUILD__Package(string $dist): string
{
	$source = BUILD_PACKAGE_SOURCES[$dist];
	$files = str_ends_with($source, '.css') ? [$source] : BUILD__Pulled($source);
	$license = str_starts_with($source, 'editor/') ? 'the editor © 2026 Red Z Group · PolyForm Strict 1.0.0, see LICENSE-editor: noncommercial use only, no changes, no redistribution' : 'MIT';
	return MIN__Bundle(BUILD_ROOT, $files, '/*! REDZ.UI · ' . $license . ' · https://github.com/redz-tech/REDZ.UI - built by tools/build.php from ' . $source . ' */')[0];
}

/** js/floor.min.js: a classic script for the page's head, before the stylesheets, that marks <html data-floor="below">
 *  when one test of tools/floor/tests.json fails, or the browser cannot run them, so that the page shows its own words
 *  in place of a broken screen. */
function BUILD__FloorJs(): string
{
	$tests = json_decode((string)file_get_contents(BUILD_ROOT . '/tools/floor/tests.json'), true, 512, JSON_THROW_ON_ERROR)['tests'];
	$lines = array_map(fn(array $test): string => "\t\t\t" . $test['test'], $tests);
	return BUILD_FLOOR_HEAD . "\n" . MIN__JsSafe("(function () {\n\tvar below = true;\n\ttry {\n\t\tbelow = !(\n" . implode(" &&\n", $lines) . "\n\t\t);\n\t} catch (error) {\n\t\tbelow = true;\n\t}\n"
		. "\tif (below) {\n\t\tdocument.documentElement.setAttribute('data-floor', 'below');\n\t}\n})();\n") . "\n";
}

/** The passport: the version, the floor, the files to link - the main three, the icon pack this release needs, the
 *  editor and the packages -, the vocabulary - every class, every custom property the stylesheets define, the commands
 *  js/commands.js stands in for, the keys the page's texts must hold (a count by its .other form) and the counts whose
 *  other plural forms the page may add - and the sha256 of every file beside it in the SRI form. */
function BUILD__Passport(): string
{
	$sheets = array_merge(...array_map(fn(string $pattern): array => glob(BUILD_ROOT . '/' . $pattern) ?: [], BUILD_STYLES));
	$css = implode("\n", array_map(fn(string $file): string => (string)file_get_contents($file), $sheets));
	preg_match_all('~(?<![\w-])(--redz-[a-z0-9-]+)\s*:~', $css, $tokens);
	$texts = (array)BUILD__Vocabulary()->texts;
	if (preg_match('~const builtIn = \[([^\]]*)\]~', (string)file_get_contents(BUILD_ROOT . '/js/commands.js'), $list) !== 1) {
		throw new RuntimeException('js/commands.js has no list builtIn of the commands it stands in for');
	}
	preg_match_all('~\'([a-z-]+)\'~', $list[1], $commands);
	$sorted = function (array $names): array {
		$names = array_values(array_unique($names));
		sort($names, SORT_STRING);
		return $names;
	};
	$floor = json_decode((string)file_get_contents(BUILD_ROOT . '/floor.json'), true, 512, JSON_THROW_ON_ERROR)['floor'];
	$files = [];
	foreach (BUILD__Archived() as $file) {
		$files[$file] = BUILD__Hash('dist/' . $file);
	}
	$encode = fn(mixed $value): string => (string)json_encode($value, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
	$list = fn(array $items): string => "[\n\t\t" . implode(",\n\t\t", array_map($encode, $items)) . "\n\t]";
	$fields = [
		'name' => $encode('REDZ.UI'),
		'version' => $encode(BUILD__Version()),
		'license' => $encode('MIT'),
		'site' => $encode('https://redz-tech.github.io/REDZ.UI/'),
		'floor' => $encode($floor),
		'main' => $encode(BUILD_MAIN),
		'icons' => $encode(BUILD_ICONS),
		'classes' => $list(array_map('strval', array_keys(TOOL__Classes()))),
		'tokens' => $list($sorted($tokens[1])),
		'commands' => $list($sorted($commands[1])),
		'texts' => $list($sorted(array_map(fn(string $key, string $kind): string => $kind === 'count' ? $key . '.other' : $key, array_keys($texts), $texts))),
		'plurals' => $list($sorted(array_keys(array_filter($texts, fn(string $kind): bool => $kind === 'count')))),
		'editor' => $encode([...BUILD_EDITOR, 'license' => 'PolyForm-Strict-1.0.0', 'rights' => BUILD_RIGHTS, 'catalog' => BUILD__Catalog()['elements'], 'write' => BUILD__WriteSchema(), 'texts' => $sorted(array_map(fn(string $key): string => 'editor.' . $key, array_keys((array)BUILD__Vocabulary()->editor->texts)))]),
		'packages' => $encode(BUILD_PACKAGES),
		'files' => "{\n\t\t" . implode(",\n\t\t", array_map(fn(string $file, string $hash): string => $encode($file) . ': ' . $encode($hash), array_keys($files), $files)) . "\n\t}",
	];
	return "{\n\t" . implode(",\n\t", array_map(fn(string $key, string $value): string => $encode($key) . ': ' . $value, array_keys($fields), $fields)) . "\n}\n";
}

/**
 * The island's keys of tools/vocabulary.json held against the scripts and the docs: every key a script asks for by
 * text('key', …) or textCount('key', …) is declared, a count as "count"; every declared key is a string in a script;
 * the docs' texts hold each one, a count by its .other form. Answers what is wrong.
 * @return list<string>
 */
function BUILD__TextsCheck(stdClass $vocab): array
{
	$js = implode("\n", array_map(fn(string $file): string => (string)file_get_contents($file), glob(BUILD_ROOT . '/js/*.js') ?: []));
	$declared = (array)$vocab->texts;
	$docs = json_decode((string)file_get_contents(__DIR__ . '/docs.json'), true, 512, JSON_THROW_ON_ERROR)['texts'] ?? [];
	$wrong = [];
	preg_match_all('~\b(text|textCount)\(\'([\w.-]+)\'~', $js, $calls, PREG_SET_ORDER);
	foreach ($calls as [, $call, $key]) {
		$kind = $call === 'textCount' ? 'count' : 'text';
		if (($declared[$key] ?? '') !== $kind) {
			$wrong[] = 'a script asks for the ' . $kind . ' "' . $key . '", which tools/vocabulary.json does not declare as one';
		}
	}
	foreach ($declared as $key => $kind) {
		if (!str_contains($js, $kind === 'count' ? 'textCount(\'' . $key . '\'' : '\'' . $key . '\'')) {
			$wrong[] = 'tools/vocabulary.json declares the ' . $kind . ' "' . $key . '", which no script asks for';
		}
		if (!isset($docs[$kind === 'count' ? $key . '.other' : $key])) {
			$wrong[] = 'tools/docs.json has no text for "' . ($kind === 'count' ? $key . '.other' : $key) . '"';
		}
	}
	$editor = implode("\n", array_map(fn(string $file): string => (string)file_get_contents($file), glob(BUILD_ROOT . '/editor/*.js') ?: []));
	$keys = (array)($vocab->editor->texts ?? []);
	preg_match_all('~\bsay(?:Count)?\(\'([\w.-]+)\'~', $editor, $asked);
	foreach (array_unique($asked[1]) as $key) {
		if (!str_ends_with($key, '.') && !isset($keys[$key])) {
			$wrong[] = 'the editor asks for the text "editor.' . $key . '", which tools/vocabulary.json\'s editor.texts does not declare';
		}
	}
	foreach ($keys as $key => $kind) {
		if (preg_match('~^(el|prop|value|tone|tab|form|lens|lock|rows|columns|ai|pair|who)\.~', (string)$key) !== 1 && !str_contains($editor, '\'' . $key . '\'')) {
			$wrong[] = 'tools/vocabulary.json declares the editor text "' . $key . '", which the editor never names';
		}
		$word = 'editor.' . $key . ($kind === 'count' ? '.other' : '');
		if (!isset($docs[$word])) {
			$wrong[] = 'tools/docs.json has no text for "' . $word . '"';
		}
	}
	return $wrong;
}

