/**
 * The calls of the tools to functions they neither define nor find in every PHP - those of an extension a server may
 * lack -, by the tokens of their sources.
 * @return list<string>
 */
function BUILD__ToolsCalls(): array
{
	$builtIn = array_fill_keys(array_map('strtolower', array_merge(...array_map(fn(string $extension): array => get_extension_funcs($extension) ?: [], BUILD_TOOLS_EXTENSIONS))), true);
	$wrong = [];
	foreach (array_filter(BUILD_TOOLS_SOURCES, fn(string $source): bool => str_ends_with($source, '.php')) as $source) {
		$tokens = array_values(array_filter(token_get_all((string)file_get_contents(BUILD_ROOT . '/' . $source)), fn(mixed $t): bool => !is_array($t) || !in_array($t[0], [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)));
		$defined = [];
		foreach ($tokens as $k => $t) {
			if (is_array($t) && $t[0] === T_FUNCTION && is_array($tokens[$k + 1] ?? null) && $tokens[$k + 1][0] === T_STRING) {
				$defined[strtolower($tokens[$k + 1][1])] = true;
			}
		}
		foreach ($tokens as $k => $t) {
			$prev = $tokens[$k - 1] ?? '';
			if (!is_array($t) || !in_array($t[0], [T_STRING, T_NAME_FULLY_QUALIFIED], true) || ($tokens[$k + 1] ?? '') !== '(' || (is_array($prev) && in_array($prev[0], [T_FUNCTION, T_OBJECT_OPERATOR, T_NULLSAFE_OBJECT_OPERATOR, T_DOUBLE_COLON, T_NEW], true))) {
				continue;
			}
			$name = strtolower(ltrim($t[1], '\\'));
			if (!isset($defined[$name]) && !isset($builtIn[$name])) {
				$wrong[] = $source . ':' . $t[2] . '  ' . $t[1] . '() is not built into every PHP';
			}
		}
	}
	return array_values(array_unique($wrong));
}

/** Why the pack differs from what its version's tag published; '' when it does not, or when no such tag is here. */
function BUILD__IconsChanged(): string
{
	$tag = 'icons-' . BUILD_ICONS['version'];
	$proc = proc_open(['git', '-C', BUILD_ROOT, 'show', 'refs/tags/' . $tag . ':' . BUILD_ICONS_PASSPORT], [1 => ['pipe', 'w'], 2 => ['file', '/dev/null', 'w']], $pipes);
	$published = is_resource($proc) ? (string)stream_get_contents($pipes[1]) : '';
	if (is_resource($proc) && proc_close($proc) !== 0) {
		return '';
	}
	$now = BUILD__IconsPassport();
	return $published === '' || $published === $now ? '' : 'the icons differ from the published ' . $tag . ': give the pack a new version in tools/build.php';
}

/**
 * The files the entry $file pulls in, depth first, each once and before the files that pull it in: a stylesheet's
 * `@import url(…)`, a module's `import … from '…'` and `import '…'`.
 * @param array<string, true> $seen
 * @return list<string>
 */
function BUILD__Pulled(string $file, array &$seen = []): array
{
	$seen[$file] = true;
	$pattern = str_ends_with($file, '.css') ? '~^@import url\("([^"]+)"\);~m' : '~^import (?:[^\'"]+ from )?\'([^\']+)\';~m';
	preg_match_all($pattern, (string)file_get_contents(BUILD_ROOT . '/' . $file), $found);
	$files = [];
	foreach ($found[1] as $relative) {
		$pulled = ltrim(str_replace('/./', '/', dirname($file) . '/' . $relative), './');
		do {
			$pulled = (string)preg_replace('~(?<![^/])[\w-]+/\.\./~', '', $pulled, 1, $folded);
		} while ($folded > 0);
		if (!is_file(BUILD_ROOT . '/' . $pulled)) {
			throw new RuntimeException($file . ' pulls in ' . $relative . ', which does not exist');
		}
		if (!isset($seen[$pulled])) {
			array_push($files, ...BUILD__Pulled($pulled, $seen));
		}
	}
	$files[] = $file;
	return $files;
}

/** The version of the changelog's newest released section, `## X.Y.Z - YYYY-MM-DD`. */
function BUILD__Version(): string
{
	if (preg_match('~^## (\d+\.\d+\.\d+) - \d{4}-\d{2}-\d{2}$~mu', (string)file_get_contents(BUILD_ROOT . '/CHANGELOG.md'), $m) !== 1) {
		throw new RuntimeException('CHANGELOG.md has no released section "## X.Y.Z - YYYY-MM-DD"');
	}
	return $m[1];
}

/**
 * The files of dist/ beside its passport, relative to dist/, sorted.
 * @return list<string>
 */
function BUILD__Archived(): array
{
	$files = [];
	foreach (BUILD_ARCHIVED as $pattern) {
		foreach (glob(BUILD_ROOT . '/dist/' . $pattern) ?: [] as $path) {
			if (is_file($path)) {
				$files[] = substr($path, strlen(BUILD_ROOT . '/dist/'));
			}
		}
	}
	sort($files, SORT_STRING);
	return $files;
}

/** The release's stylesheet or script - dist/css/redz-ui.min.css or dist/js/redz-ui.min.js - built and proved by tools/min.php. */
function BUILD__Dist(string $kind): string
{
	$files = $kind === 'css' ? array_slice(BUILD__Pulled('css/index.css'), 0, -1) : BUILD__Pulled('js/index.js');
	return MIN__Bundle(BUILD_ROOT, $files, BUILD_DIST_HEAD)[0];
}

/** A package file of dist/, from its source by tools/min.php: a stylesheet squeezed, a module joined with the modules it
 *  imports - the editor with js/text.js - and given short names. */
function BUILD__Package(string $dist): string
{
	$source = BUILD_PACKAGE_SOURCES[$dist];
	$files = str_ends_with($source, '.css') ? [$source] : BUILD__Pulled($source);
	return MIN__Bundle(BUILD_ROOT, $files, str_starts_with($source, 'editor/') ? BUILD_EDITOR_HEAD : BUILD_DIST_HEAD)[0];
}

/** js/floor.min.js: a classic script for the page's head, before the stylesheets, that marks <html data-floor="below">
 *  when one test of tools/floor/tests.json fails, or the browser cannot run them, so that the page shows its own words
 *  in place of a broken screen. */
function BUILD__FloorJs(): string
{
	$tests = json_decode((string)file_get_contents(BUILD_ROOT . '/tools/floor/tests.json'), true, 512, JSON_THROW_ON_ERROR)['tests'];
	$lines = array_map(fn(array $test): string => "\t\t\t" . $test['test'], $tests);
	return BUILD_DIST_HEAD . "\n" . MIN__JsSafe("(function () {\n\tvar below = true;\n\ttry {\n\t\tbelow = !(\n" . implode(" &&\n", $lines) . "\n\t\t);\n\t} catch (error) {\n\t\tbelow = true;\n\t}\n"
		. "\tif (below) {\n\t\tdocument.documentElement.setAttribute('data-floor', 'below');\n\t}\n})();\n") . "\n";
}

/** The passport: the version, the floor, the files to link - the main three, the icon pack this release needs, the
 *  editor and the packages -, the vocabulary - every class, every custom property the stylesheets define, the commands
 *  js/commands.js stands in for and every -- command the scripts handle, the keys the page's texts must hold (a count by its .other form), the counts whose
 *  other plural forms the page may add and the {names} each of those texts is given - and the sha256 of every file
 *  beside it in the SRI form. */
function BUILD__Passport(): string
{
	$sheets = array_merge(...array_map(fn(string $pattern): array => glob(BUILD_ROOT . '/' . $pattern) ?: [], BUILD_STYLES));
	$css = implode("\n", array_map(fn(string $file): string => (string)file_get_contents($file), $sheets));
	preg_match_all('~(?<![\w-])(--redz-[a-z0-9-]+)\s*:~', $css, $tokens);
	$texts = (array)BUILD__Vocabulary()->texts;
	if (preg_match('~const builtIn = \[([^\]]*)\]~', (string)file_get_contents(BUILD_ROOT . '/js/commands.js'), $list) !== 1) {
		throw new RuntimeException('js/commands.js has no list builtIn of the commands it stands in for');
	}
	preg_match_all('~\'([a-z-]+)\'~', $list[1], $commands);
	$sorted = function (array $names): array {
		$names = array_values(array_unique($names));
		sort($names, SORT_STRING);
		return $names;
	};
	$floor = json_decode((string)file_get_contents(BUILD_ROOT . '/floor.json'), true, 512, JSON_THROW_ON_ERROR)['floor'];
	$files = [];
	foreach (BUILD__Archived() as $file) {
		$files[$file] = BUILD__Hash('dist/' . $file);
	}
	$encode = fn(mixed $value): string => (string)json_encode($value, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
	$list = fn(array $items): string => "[\n\t\t" . implode(",\n\t\t", array_map($encode, $items)) . "\n\t]";
	$args = [];
	foreach (BUILD__MainArgs(BUILD__Vocabulary())[0] as $key => $names) {
		$args[$texts[$key] === 'count' ? $key . '.other' : $key] = $names;
		if ($texts[$key] === 'count') {
			$args[$key] = $names;
		}
	}
	ksort($args, SORT_STRING);
	$fields = [
		'name' => $encode('REDZ.UI'),
		'version' => $encode(BUILD__Version()),
		'license' => $encode('MIT'),
		'site' => $encode('https://redz-tech.github.io/REDZ.UI/'),
		'floor' => $encode($floor),
		'main' => $encode(BUILD_MAIN),
		'icons' => $encode(BUILD_ICONS),
		'classes' => $list(array_map('strval', array_keys(TOOL__Classes()))),
		'tokens' => $list($sorted($tokens[1])),
		'commands' => $list($sorted([...$commands[1], ...BUILD__CustomCommands()])),
		'texts' => $list($sorted(array_map(fn(string $key, string $kind): string => $kind === 'count' ? $key . '.other' : $key, array_keys($texts), $texts))),
		'plurals' => $list($sorted(array_keys(array_filter($texts, fn(string $kind): bool => $kind === 'count')))),
		'args' => "{\n\t\t" . implode(",\n\t\t", array_map(fn(string $key, array $names): string => $encode($key) . ': ' . $encode($names), array_keys($args), $args)) . "\n\t}",
		'editor' => $encode([...BUILD_EDITOR, 'license' => 'PolyForm-Strict-1.0.0', 'rights' => BUILD_RIGHTS, 'catalog' => BUILD__Catalog()['elements'], 'write' => BUILD__WriteSchema(), 'texts' => $sorted(array_map(fn(string $key): string => 'editor.' . $key, array_keys((array)BUILD__Vocabulary()->editor->texts))), 'args' => (object)array_combine(array_map(fn(string $key): string => 'editor.' . $key, array_keys(BUILD__EditorArgs(BUILD__Vocabulary())[0])), BUILD__EditorArgs(BUILD__Vocabulary())[0])]),
		'packages' => $encode(BUILD_PACKAGES),
		'files' => "{\n\t\t" . implode(",\n\t\t", array_map(fn(string $file, string $hash): string => $encode($file) . ': ' . $encode($hash), array_keys($files), $files)) . "\n\t}",
	];
	return "{\n\t" . implode(",\n\t", array_map(fn(string $key, string $value): string => $encode($key) . ': ' . $value, array_keys($fields), $fields)) . "\n}\n";
}

/**
 * The names of the object literal that opens at the byte: its keys, written out or short, outside strings and nested
 * brackets. A spread names none it can tell.
 * @return list<string>
 */
function BUILD__ObjectKeys(string $js, int $at): array
{
	$depth = 0;
	$part = '';
	$parts = [];
	for ($i = $at, $length = strlen($js); $i < $length; $i++) {
		$char = $js[$i];
		if ($char === '\'' || $char === '"' || $char === '`') {
			$end = $i + 1;
			while ($end < $length && $js[$end] !== $char) {
				$end += $js[$end] === '\\' ? 2 : 1;
			}
			$part .= substr($js, $i, $end - $i + 1);
			$i = $end;
			continue;
		}
		if (str_contains('([{', $char)) {
			$depth++;
		} elseif (str_contains(')]}', $char)) {
			if ($depth === 0) {
				$parts[] = $part;
				break;
			}
			$depth--;
		} elseif ($char === ',' && $depth === 0) {
			$parts[] = $part;
			$part = '';
			continue;
		}
		$part .= $char;
	}
	$names = [];
	foreach ($parts as $one) {
		if (trim($one) === '') {
			continue;
		}
		if (preg_match('~^\s*([A-Za-z_$][\w$]*)\s*(?::|$)~', $one, $name) !== 1) {
			throw new RuntimeException('a text call passes "' . trim($one) . '", whose name the build cannot read');
		}
		$names[] = $name[1];
	}
	sort($names, SORT_STRING);
	return array_values(array_unique($names));
}

/**
 * The {names} each declared text is given, by its key, read from the scripts: a call CALL('key', {…}), or an object
 * {key: 'key', args: {…}} the editor says later; a count's {count}; none for a key no call names whole (one built
 * from a variable). Answers the names by key and the keys whose calls pass different ones.
 * @param array<string, string> $declared
 * @return array{array<string, list<string>>, list<string>}
 */
function BUILD__TextArgs(array $declared, string $pattern, string $call): array
{
	$js = implode("\n", array_map(fn(string $file): string => (string)file_get_contents($file), glob(BUILD_ROOT . '/' . $pattern) ?: []));
	$args = [];
	foreach ($declared as $key => $kind) {
		$args[$key] = $kind === 'count' ? ['count'] : [];
	}
	$seen = [];
	$differ = [];
	preg_match_all('~(?:\b' . $call . '\(|\bkey:\s*)\'([\w.-]+)\'(\s*,\s*(?:args:\s*)?\{)?~', $js, $calls, PREG_SET_ORDER | PREG_OFFSET_CAPTURE);
	foreach ($calls as $one) {
		$key = $one[1][0];
		if (!isset($args[$key]) || ($declared[$key] ?? '') === 'count') {
			continue;
		}
		$names = isset($one[2]) && $one[2][1] >= 0 ? BUILD__ObjectKeys($js, $one[2][1] + strlen($one[2][0])) : [];
		if (isset($seen[$key]) && $seen[$key] !== $names) {
			$differ[] = $key;
		}
		$seen[$key] = $names;
		$args[$key] = $names;
	}
	ksort($args, SORT_STRING);
	return [$args, array_values(array_unique($differ))];
}

/** The {names} of the main texts, read from js/*.js. */
function BUILD__MainArgs(stdClass $vocab): array
{
	return BUILD__TextArgs((array)$vocab->texts, 'js/*.js', 'text');
}

/** The {names} of the editor's texts, read from editor/*.js. */
function BUILD__EditorArgs(stdClass $vocab): array
{
	return BUILD__TextArgs((array)($vocab->editor->texts ?? []), 'editor/*.js', 'say');
}

/**
 * The -- commands the library's scripts handle: their strings of two dashes and a name, less the names the stylesheets
 * use as custom properties.
 * @return list<string>
 */
function BUILD__CustomCommands(): array
{
	$sheets = array_merge(...array_map(fn(string $pattern): array => glob(BUILD_ROOT . '/' . $pattern) ?: [], BUILD_STYLES));
	$css = implode("\n", array_map(fn(string $file): string => (string)file_get_contents($file), $sheets));
	preg_match_all('~(?|var\(\s*(--[a-z][a-z0-9-]*)|(?<![\w-])(--[a-z][a-z0-9-]*)\s*:)~', $css, $properties);
	$names = [];
	foreach (['js', 'editor', 'charts', 'calendar', 'media', 'qr'] as $folder) {
		foreach (glob(BUILD_ROOT . '/' . $folder . '/*.js') ?: [] as $file) {
			preg_match_all('~[\'"`](--(?!redz-)[a-z][a-z-]*)[\'"`]~', (string)file_get_contents($file), $found);
			array_push($names, ...$found[1]);
		}
	}
	return array_values(array_diff(array_unique($names), $properties[1]));
}

/**
 * The -- commands held against the docs: each one a script handles is shown in docs/src, and each one shown there is
 * handled. Answers what is wrong.
 * @return list<string>
 */
function BUILD__CommandsCheck(): array
{
	$handled = BUILD__CustomCommands();
	$docs = implode("\n", array_map(fn(string $file): string => (string)file_get_contents($file), glob(BUILD_ROOT . '/docs/src/*.html') ?: []));
	preg_match_all('~\bcommand="(--[a-z-]+)"~', $docs, $found);
	$shown = array_values(array_unique($found[1]));
	return [
		...array_map(fn(string $name): string => 'a script handles the command ' . $name . ', which docs/src never shows', array_values(array_diff($handled, $shown))),
		...array_map(fn(string $name): string => 'docs/src shows the command ' . $name . ', which no script handles', array_values(array_diff($shown, $handled))),
	];
}

/**
 * The markup a consumer copies, docs/src and the demo screens: each class is the library's or a page's own docs- or demo-
 * name, each control has an id or a name, and a div, a span or a pre with a name has a role. Answers what is wrong.
 * @return list<string>
 */
function BUILD__SamplesCheck(): array
{
	$classes = TOOL__Classes();
	$wrong = [];
	foreach ([...glob(BUILD_ROOT . '/docs/src/*.html') ?: [], ...glob(BUILD_ROOT . '/reference/demo/*.html') ?: []] as $file) {
		$where = substr($file, strlen(BUILD_ROOT) + 1);
		preg_match_all('~<([a-z][a-z0-9]*)\b((?:[^>"\']|"[^"]*"|\'[^\']*\')*)>~', (string)file_get_contents($file), $tags, PREG_SET_ORDER);
		foreach ($tags as [, $tag, $attributes]) {
			preg_match_all('~\s([a-z][a-z-]*)(?:="([^"]*)")?~', $attributes, $pairs, PREG_SET_ORDER);
			$has = array_column($pairs, 2, 1);
			foreach (preg_split('~\s+~', trim($has['class'] ?? ''), -1, PREG_SPLIT_NO_EMPTY) ?: [] as $class) {
				if (!isset($classes[$class]) && !preg_match('~^(docs|demo)-~', $class)) {
					$wrong[] = $where . '  the class ' . $class . ' is in no stylesheet';
				}
			}
			if (in_array($tag, ['input', 'select', 'textarea'], true) && ($has['type'] ?? '') !== 'hidden' && !isset($has['id']) && !isset($has['name'])) {
				$wrong[] = $where . '  a ' . $tag . ' has neither an id nor a name: ' . ($has['aria-label'] ?? $has['placeholder'] ?? $has['type'] ?? '');
			}
			if (in_array($tag, ['div', 'span', 'pre'], true) && (isset($has['aria-label']) || isset($has['aria-labelledby'])) && !isset($has['role'])) {
				$wrong[] = $where . '  a ' . $tag . ' with a name has no role: ' . ($has['class'] ?? '');
			}
		}
	}
	return $wrong;
}

/**
 * The bodies of the @media blocks of $query in $css, and $css without them.
 * @return array{list<string>, string}
 */
function BUILD__MediaBlocks(string $css, string $query): array
{
	$bodies = [];
	while (($at = strpos($css, $query)) !== false) {
		$open = (int)strpos($css, '{', $at);
		$depth = 1;
		$end = $open + 1;
		while ($depth > 0 && $end < strlen($css)) {
			$depth += ['{' => 1, '}' => -1][$css[$end++]] ?? 0;
		}
		$bodies[] = substr($css, $open + 1, $end - $open - 2);
		$css = substr($css, 0, $at) . substr($css, $end);
	}
	return [$bodies, $css];
}

/**
 * An endless animation outside a no-preference block runs for a person who asks for less motion, so that it says work
 * goes on: each one is slowed in a reduce block of its own stylesheet. Answers what is wrong.
 * @return list<string>
 */
function BUILD__MotionCheck(): array
{
	$split = fn(string $selectors): array => array_map(fn(string $selector): string => trim((string)preg_replace('~\s+~', ' ', $selector)), explode(',', $selectors));
	$wrong = [];
	foreach (array_merge(...array_map(fn(string $pattern): array => glob(BUILD_ROOT . '/' . $pattern) ?: [], BUILD_STYLES)) as $file) {
		[, $css] = BUILD__MediaBlocks((string)preg_replace('~/\*.*?\*/~s', '', (string)file_get_contents($file)), '@media (prefers-reduced-motion: no-preference)');
		[$reduce, $css] = BUILD__MediaBlocks($css, '@media (prefers-reduced-motion: reduce)');
		preg_match_all('~([^{}]+)\{[^{}]*\banimation-duration:[^{}]*\}~', implode("\n", $reduce), $slowed);
		preg_match_all('~([^{}]+)\{[^{}]*\banimation:[^;{}]*\binfinite\b[^{}]*\}~', $css, $endless);
		$missing = array_diff(array_merge([], ...array_map($split, $endless[1])), array_merge([], ...array_map($split, $slowed[1])));
		foreach ($missing as $selector) {
			$wrong[] = substr($file, strlen(BUILD_ROOT) + 1) . '  ' . $selector . ' runs without end and is not slowed for less motion';
		}
	}
	return $wrong;
}

/**
 * The island's keys of tools/vocabulary.json held against the scripts and the docs: every key a script asks for by
 * text('key', …) or textCount('key', …) is declared, a count as "count"; every declared key is a string in a script;
 * the docs' texts hold each one, a count by its .other form. Answers what is wrong.
 * @return list<string>
 */
function BUILD__TextsCheck(stdClass $vocab): array
{
	$js = implode("\n", array_map(fn(string $file): string => (string)file_get_contents($file), glob(BUILD_ROOT . '/js/*.js') ?: []));
	$declared = (array)$vocab->texts;
	$docs = json_decode((string)file_get_contents(__DIR__ . '/docs.json'), true, 512, JSON_THROW_ON_ERROR)['texts'] ?? [];
	$wrong = [];
	preg_match_all('~\b(text|textCount)\(\'([\w.-]+)\'~', $js, $calls, PREG_SET_ORDER);
	foreach ($calls as [, $call, $key]) {
		$kind = $call === 'textCount' ? 'count' : 'text';
		if (($declared[$key] ?? '') !== $kind) {
			$wrong[] = 'a script asks for the ' . $kind . ' "' . $key . '", which tools/vocabulary.json does not declare as one';
		}
	}
	foreach ($declared as $key => $kind) {
		if (!str_contains($js, $kind === 'count' ? 'textCount(\'' . $key . '\'' : '\'' . $key . '\'')) {
			$wrong[] = 'tools/vocabulary.json declares the ' . $kind . ' "' . $key . '", which no script asks for';
		}
		if (!isset($docs[$kind === 'count' ? $key . '.other' : $key])) {
			$wrong[] = 'tools/docs.json has no text for "' . ($kind === 'count' ? $key . '.other' : $key) . '"';
		}
	}
	foreach (['' => [BUILD__MainArgs($vocab), $declared], 'editor.' => [BUILD__EditorArgs($vocab), (array)($vocab->editor->texts ?? [])]] as $prefix => [[$args, $differ], $kinds]) {
		foreach ($differ as $key) {
			$wrong[] = 'the scripts call the text "' . $prefix . $key . '" with different names';
		}
		foreach ($args as $key => $names) {
			$words = $kinds[$key] === 'count' ? array_filter(array_keys($docs), fn(string $word): bool => str_starts_with($word, $prefix . $key . '.')) : [$prefix . $key];
			foreach (array_filter($words, fn(string $word): bool => isset($docs[$word])) as $word) {
				preg_match_all('~\{(\w+)\}~', (string)$docs[$word], $used);
				$used = array_values(array_unique($used[1]));
				sort($used, SORT_STRING);
				if ($used !== $names) {
					$wrong[] = 'tools/docs.json\'s "' . $word . '" uses {' . implode('}, {', $used) . '}, and its calls pass {' . implode('}, {', $names) . '}';
				}
			}
		}
	}
	$editor = implode("\n", array_map(fn(string $file): string => (string)file_get_contents($file), glob(BUILD_ROOT . '/editor/*.js') ?: []));
	$keys = (array)($vocab->editor->texts ?? []);
	preg_match_all('~\bsay(?:Count)?\(\'([\w.-]+)\'~', $editor, $asked);
	foreach (array_unique($asked[1]) as $key) {
		if (!str_ends_with($key, '.') && !isset($keys[$key])) {
			$wrong[] = 'the editor asks for the text "editor.' . $key . '", which tools/vocabulary.json\'s editor.texts does not declare';
		}
	}
	foreach ($keys as $key => $kind) {
		if (preg_match('~^(el|prop|value|tone|tab|form|lens|lock|rows|columns|ai|pair|who)\.~', (string)$key) !== 1 && !str_contains($editor, '\'' . $key . '\'')) {
			$wrong[] = 'tools/vocabulary.json declares the editor text "' . $key . '", which the editor never names';
		}
		$word = 'editor.' . $key . ($kind === 'count' ? '.other' : '');
		if (!isset($docs[$word])) {
			$wrong[] = 'tools/docs.json has no text for "' . $word . '"';
		}
	}
	return $wrong;
}

