/** $text with $by before each line, but not before the lines that continue a <pre>. */
function DOCS__Indent(string $text, string $by): string
{
	$out = [];
	$inside = false;
	foreach (explode("\n", $text) as $line) {
		$out[] = $inside || $line === '' ? $line : $by . $line;
		$inside = preg_match('~<pre[\s>](?!.*</pre>)~', $line) === 1 || ($inside && !str_contains($line, '</pre>'));
	}
	return implode("\n", $out);
}

/** The body of a source: its markup indented into the article, the code printed, the generated sections added. */
function DOCS__Body(string $key, string $html, array $rows): string
{
	$body = DOCS__WithCode($html);
	$filled = ['<!-- docs:map -->' => fn(): string => DOCS__MapTable($rows), '<!-- docs:utilities -->' => DOCS__UtilitiesTable(...), '<!-- docs:tokens -->' => DOCS__TokensTable(...)];
	foreach ($filled as $mark => $make) {
		if (str_contains($body, $mark)) {
			$body = str_replace($mark, trim($make()), $body);
		}
	}
	$body = rtrim($body) . "\n" . DOCS__TokensSection($key) . DOCS__MapSection($key, $rows);
	return DOCS__Indent(rtrim($body), "\t\t\t\t");
}

/** A table of every utility class of tools/vocabulary.json with its declarations, and the conditions it takes. */
function DOCS__UtilitiesTable(): string
{
	$css = (string)file_get_contents(DOCS_ROOT . '/css/utilities.css');
	preg_match_all('~^\t\.((?:[^\\\\ ]|\\\\.)+) \{ (.*) \}$~m', $css, $rules, PREG_SET_ORDER);
	$prefixed = [];
	preg_match_all('~^\t\t\.(?:\\\\32 )?[a-z0-9]*\\\\:((?:[^\\\\ ]|\\\\.)+) \{~m', $css, $more);
	foreach ($more[1] as $class) {
		$prefixed[stripslashes($class)] = true;
	}
	$out = "\t\t\t<table class=\"table docs-table\">\n\t\t\t\t<thead><tr><th scope=\"col\">Class</th><th scope=\"col\">Declarations</th><th scope=\"col\">Width prefixes</th></tr></thead>\n\t\t\t\t<tbody>\n";
	foreach ($rules as [, $class, $declarations]) {
		$class = stripslashes($class);
		$out .= "\t\t\t\t\t<tr><td><code>" . htmlspecialchars($class) . '</code></td><td><code>' . htmlspecialchars($declarations) . '</code></td><td>' . (isset($prefixed[$class]) ? 'yes' : '—') . "</td></tr>\n";
	}
	return $out . "\t\t\t\t</tbody>\n\t\t\t</table>\n";
}

/** A table of the theme's tokens on :root, each with its value in the light theme. */
function DOCS__TokensTable(): string
{
	$css = (string)file_get_contents(DOCS_ROOT . '/css/tokens.css') . (string)file_get_contents(DOCS_ROOT . '/css/scales.css');
	preg_match_all('~^\t\t(--redz-[a-z0-9-]+): ([^;]+);~m', $css, $tokens, PREG_SET_ORDER);
	$seen = [];
	$out = "\t\t\t<table class=\"table docs-table\">\n\t\t\t\t<thead><tr><th scope=\"col\">Token</th><th scope=\"col\">Value</th></tr></thead>\n\t\t\t\t<tbody>\n";
	foreach ($tokens as [, $name, $value]) {
		if (isset($seen[$name])) {
			continue;
		}
		$seen[$name] = true;
		$out .= "\t\t\t\t\t<tr><td><code>" . $name . '</code></td><td><code>' . htmlspecialchars($value) . "</code></td></tr>\n";
	}
	return $out . "\t\t\t\t</tbody>\n\t\t\t</table>\n";
}

/** The all-components page: every example and state grid of every page, under the page's name. */
function DOCS__All(array $config, array $sources): string
{
	$body = "<header class=\"vstack gap-8\">\n\t<h1>All components</h1>\n\t<p class=\"docs-lead\">Every example and every state of every page on one page — the fixture the probes shoot in each engine, at each width, in both themes and directions, in forced colors and in print.</p>\n</header>\n";
	foreach ($config['pages'] as $key => [$title]) {
		$blocks = [...DOCS__Blocks($sources[$key]['html'], 'docs-example'), ...DOCS__Blocks($sources[$key]['html'], 'docs-states')];
		if ($blocks === []) {
			continue;
		}
		usort($blocks, fn(array $a, array $b): int => $a[0] <=> $b[0]);
		$body .= "\n<section class=\"vstack gap-16\" aria-labelledby=\"all-" . $key . "\">\n\t<h2 id=\"all-" . $key . '"><a href="' . $key . '.html">' . htmlspecialchars($title) . "</a></h2>\n";
		foreach ($blocks as [$start, $end, , $indent]) {
			$block = substr($sources[$key]['html'], $start, $end - $start);
			$body .= "\t" . preg_replace('~\n' . preg_quote($indent, '~') . '~', "\n\t", $block) . "\n";
		}
		$body .= "</section>\n";
	}
	return DOCS__Indent(rtrim($body), "\t\t\t\t");
}

/**
 * The translation table of $file: English => the other language, one tab-separated pair a line.
 * @return array<string, string>
 */
function DOCS__Table(string $file): array
{
	$table = [];
	foreach (explode("\n", (string)@file_get_contents(DOCS_ROOT . '/' . $file)) as $line) {
		if (str_contains($line, "\t") && !str_starts_with($line, '#')) {
			[$from, $to] = explode("\t", $line, 2);
			$table[$from] = $to;
		}
	}
	return $table;
}

/** The text in the other language, its surrounding white space kept; what the table lacks goes to $missing. */
function DOCS__Translated(string $text, array $table, array &$missing): string
{
	$plain = trim((string)preg_replace('~\s+~u', ' ', $text));
	if ($plain === '' || preg_match('~\p{L}~u', $plain) !== 1) {
		return $text;
	}
	if (!isset($table[$plain])) {
		$missing[$plain] = true;
		return $text;
	}
	preg_match('~^(\s*).*?(\s*)$~su', $text, $edges);
	return $edges[1] . $table[$plain] . $edges[2];
}

/** Translates the texts and named attributes under $node, but not inside code, scripts or translate="no". */
function DOCS__TwinWalk(Dom\Node $node, array $table, array &$missing): void
{
	foreach ($node->childNodes as $child) {
		if ($child instanceof Dom\Text) {
			$child->data = DOCS__Translated($child->data, $table, $missing);
			continue;
		}
		if (!$child instanceof Dom\Element || in_array($child->localName, DOCS_KEPT, true) || $child->getAttribute('translate') === 'no' || ($child->localName === 'th' && $child->closest('.docs-matrix') !== null)) {
			continue;
		}
		foreach (DOCS_NAMED as $name) {
			if ($child->hasAttribute($name)) {
				$child->setAttribute($name, DOCS__Translated((string)$child->getAttribute($name), $table, $missing));
			}
		}
		DOCS__TwinWalk($child, $table, $missing);
	}
}

/** The twin of $html in $lang, right to left: every text, named attribute, title and the island translated. */
function DOCS__Twin(string $html, string $lang, array $table, array &$missing): string
{
	$doc = Dom\HTMLDocument::createFromString($html, LIBXML_NOERROR);
	$doc->documentElement->setAttribute('lang', $lang);
	$doc->documentElement->setAttribute('dir', 'rtl');
	DOCS__TwinWalk($doc->body, $table, $missing);
	$doc->title = DOCS__Translated($doc->title, $table, $missing);
	$island = $doc->getElementById('redz-ui-text');
	if ($island !== null) {
		$texts = json_decode($island->textContent, true) ?: [];
		foreach ($texts as $name => $value) {
			$texts[$name] = DOCS__Translated($value, $table, $missing);
		}
		$island->textContent = json_encode($texts, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_HEX_TAG | JSON_HEX_AMP);
	}
	return $doc->saveHtml() . "\n";
}

/** Markdown of the inline content of $node. */
function DOCS__InlineMarkdown(Dom\Node $node): string
{
	$out = '';
	foreach ($node->childNodes as $child) {
		if ($child instanceof Dom\Text) {
			$out .= preg_replace('~\s+~u', ' ', $child->data);
			continue;
		}
		if (!$child instanceof Dom\Element || in_array($child->localName, ['script', 'style', 'template'], true)) {
			continue;
		}
		$inner = DOCS__InlineMarkdown($child);
		$out .= match ($child->localName) {
			'code', 'kbd' => '`' . $child->textContent . '`',
			'strong', 'b' => '**' . trim($inner) . '**',
			'em', 'i' => trim($inner) === '' ? '' : '_' . trim($inner) . '_',
			'a' => '[' . trim($inner) . '](' . $child->getAttribute('href') . ')',
			'br' => "\n",
			default => $inner,
		};
	}
	return $out;
}

/** Markdown of the block content of $node. */
function DOCS__BlockMarkdown(Dom\Node $node): string
{
	$out = '';
	foreach ($node->childNodes as $child) {
		if (!$child instanceof Dom\Element) {
			continue;
		}
		$class = ' ' . $child->getAttribute('class') . ' ';
		$name = $child->localName;
		if (str_contains($class, ' docs-example ') || str_contains($class, ' docs-states ') || $name === 'footer') {
			continue;
		}
		$out .= match (true) {
			in_array($name, ['h1', 'h2', 'h3', 'h4'], true) => str_repeat('#', (int)$name[1]) . ' ' . trim(DOCS__InlineMarkdown($child)) . "\n\n",
			$name === 'p' => trim(DOCS__InlineMarkdown($child)) . "\n\n",
			$name === 'pre' => '```' . (str_starts_with(ltrim($child->textContent), '<') ? 'html' : 'js') . "\n" . rtrim($child->textContent) . "\n```\n\n",
			$name === 'ul' || $name === 'ol' => implode('', array_map(fn(Dom\Element $li): string => ($name === 'ul' ? '- ' : '1. ') . trim(DOCS__InlineMarkdown($li)) . "\n", iterator_to_array($child->getElementsByTagName('li')))) . "\n",
			$name === 'table' => DOCS__TableMarkdown($child),
			default => DOCS__BlockMarkdown($child),
		};
	}
	return $out;
}

/** A Markdown table of an HTML table. */
function DOCS__TableMarkdown(Dom\Element $table): string
{
	$rows = [];
	foreach ($table->getElementsByTagName('tr') as $tr) {
		$cells = [];
		foreach ($tr->childNodes as $cell) {
			if ($cell instanceof Dom\Element && ($cell->localName === 'td' || $cell->localName === 'th')) {
				$cells[] = str_replace('|', '\|', trim(DOCS__InlineMarkdown($cell)));
			}
		}
		$rows[] = '| ' . implode(' | ', $cells) . ' |';
	}
	if ($rows === []) {
		return '';
	}
	array_splice($rows, 1, 0, '|' . str_repeat(' --- |', substr_count($rows[0], ' | ') + 1));
	return implode("\n", $rows) . "\n\n";
}

/** The Markdown twin of a generated page: its article, examples as their code, links to other pages as their twins. */
function DOCS__Markdown(string $html, string $from, string $site): string
{
	$doc = Dom\HTMLDocument::createFromString($html, LIBXML_NOERROR);
	$article = $doc->querySelector('article.docs');
	foreach ($article->querySelectorAll('a[href]') as $link) {
		$href = (string)$link->getAttribute('href');
		$href = preg_match('~^[a-z0-9-]+\.html(#.*)?$~', $href) === 1 ? (string)preg_replace('~\.html~', '.md', $href, 1) : $href;
		$link->setAttribute('href', str_starts_with($href, '../') ? $site . substr($href, 3) : $href);
	}
	return '<!-- ' . $from . " -->\n\n" . rtrim(DOCS__BlockMarkdown($article)) . "\n";
}

/**
 * llms.txt and llms-full.txt: the site in brief with a link to each page's Markdown, and every page in full.
 * @return array<string, string>
 */
function DOCS__Llms(array $config, array $sources, array $markdown): array
{
	$brief = "# REDZ.UI\n\n> The interface library of the REDZ products: plain CSS and small JavaScript on the browser platform — no framework, no build step.\n\n";
	$brief .= "Bootstrap 5's class names (Bootstrap 6's where it moved onto the platform), the number in a class is its value in pixels, a state is an HTML attribute, behavior comes from the browser's invoker commands. Browsers: Chrome and Edge 130+, Firefox 132+, Safari 18+.\n";
	$group = '';
	foreach ($config['pages'] as $key => [$title, $in]) {
		if ($in !== $group) {
			$brief .= "\n## " . $in . "\n\n";
			$group = $in;
		}
		$brief .= '- [' . $title . '](docs/' . $key . '.md): ' . $sources[$key]['lead'] . "\n";
	}
	$brief .= "\n## Skills\n\n- [redz-ui](skills/redz-ui/SKILL.md): build screens with REDZ.UI\n- [redz-ui-from-bootstrap-5](skills/redz-ui-from-bootstrap-5/SKILL.md): move a project from Bootstrap 5.3 to REDZ.UI\n";
	$full = "# REDZ.UI — the documentation in full\n";
	foreach ($markdown as $text) {
		$full .= "\n" . preg_replace('~^<!--.*?-->\n\n~', '', $text);
	}
	return ['llms.txt' => $brief, 'llms-full.txt' => $full];
}

/**
 * Every generated file: path => content; the sources' broken rules and the twins' missing translations land in $errors.
 * @return array<string, string>
 */
function DOCS__Files(array &$errors): array
{
	$config = DOCS__Config();
	$rows = DOCS__MapRows();
	$sources = [];
	foreach (array_keys($config['pages']) as $key) {
		$sources[$key] = DOCS__Source($key);
		array_push($errors, ...$sources[$key]['errors']);
	}
	if ($errors !== []) {
		return [];
	}
	$files = [];
	$markdown = [];
	foreach ($config['pages'] as $key => [$title]) {
		$from = DOCS_MARK . ' from docs/src/' . $key . '.html — edit the source, not this file.';
		$files['docs/' . $key . '.html'] = DOCS__Page($config, $key, $sources[$key]['title'], $sources[$key]['lead'], DOCS__Body($key, $sources[$key]['html'], $rows), $from);
		$files['docs/' . $key . '.md'] = $markdown[$key] = DOCS__Markdown($files['docs/' . $key . '.html'], $from, $config['site']);
		$files['skills/redz-ui/references/' . $key . '.md'] = $markdown[$key];
	}
	$files['docs/all.html'] = DOCS__Page($config, 'all', 'All components', 'Every example and every state of every page on one page.', DOCS__All($config, $sources), DOCS_MARK . ' from the examples and state grids of docs/src/ — edit the sources, not this file.');
	foreach ($config['twins'] as $lang => $pages) {
		$table = DOCS__Table('docs/' . $lang . '.tsv');
		$missing = [];
		foreach ($pages as $page) {
			$html = $files[$page] ?? (string)file_get_contents(DOCS_ROOT . '/' . $page);
			$twin = DOCS__Twin($html, $lang, $table, $missing);
			$files[substr($page, 0, -5) . '.' . $lang . '.html'] = (string)preg_replace('~<html~', "<!-- " . DOCS_MARK . ' from ' . $page . ' and docs/' . $lang . ".tsv — edit those, not this file. -->\n<html", $twin, 1);
		}
		foreach (array_keys($missing) as $text) {
			$errors[] = 'docs/' . $lang . '.tsv has no translation of "' . $text . '"';
		}
	}
	return $files + DOCS__Llms($config, $sources, $markdown);
}

/**
 * Writes the generated files and removes the ones no source makes any more, or with --check only compares; the exit
 * code.
 * @param list<string> $argv
 */
function DOCS__Main(array $argv): int
{
	$check = in_array('--check', $argv, true);
	$errors = [];
	$files = DOCS__Files($errors);
	foreach ($errors as $error) {
		fwrite(STDERR, $error . "\n");
	}
	if ($files === []) {
		return 1;
	}
	$stale = [];
	foreach ($files as $file => $text) {
		$path = DOCS_ROOT . '/' . $file;
		if (is_file($path) && file_get_contents($path) === $text) {
			continue;
		}
		if ($check) {
			$stale[] = $file;
			continue;
		}
		@mkdir(dirname($path), 0777, true);
		file_put_contents($path, $text);
		echo 'wrote ', $file, "\n";
	}
	foreach ([...glob(DOCS_ROOT . '/docs/*.{html,md}', GLOB_BRACE), ...glob(DOCS_ROOT . '/reference/demo/*.html'), ...glob(DOCS_ROOT . '/skills/redz-ui/references/*.md')] as $path) {
		$file = substr($path, strlen(DOCS_ROOT) + 1);
		if (!isset($files[$file]) && str_contains((string)file_get_contents($path, false, null, 0, 400), DOCS_MARK)) {
			if ($check) {
				$stale[] = $file . ' (no source makes it)';
				continue;
			}
			unlink($path);
			echo 'removed ', $file, "\n";
		}
	}
	if ($stale !== []) {
		fwrite(STDERR, 'out of date: ' . implode(', ', $stale) . " — run php tools/docs.php\n");
		return 1;
	}
	return $errors === [] ? 0 : 1;
}

exit(DOCS__Main($argv));
