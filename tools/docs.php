<?php
// docs — writes the site's documentation from docs/src/: each page inside the docs shell (the page list of
// tools/docs.json, the code of every example printed from the example's own markup, the custom properties a
// component's stylesheet declares and reads, its rows of the Bootstrap 5.3 map); docs/all.html — every example and
// state grid of every page, the fixture the probes shoot in every engine; the Arabic twins of tools/docs.json's "twins"
// through docs/ar.tsv; a Markdown twin of every page, llms.txt and llms-full.txt. Usage: php tools/docs.php [--check]
// — --check writes nothing and exits 1 when a file is out of date, a source breaks a rule or a twin lacks a translation.

const DOCS_ROOT = __DIR__ . '/..';
const DOCS_MARK = 'Generated by tools/docs.php';
const DOCS_MAP = 'skills/redz-ui-from-bootstrap-5/assets/map.tsv';
const DOCS_NAMED = ['aria-label', 'title', 'placeholder', 'alt', 'label'];
const DOCS_KEPT = ['code', 'pre', 'kbd', 'samp', 'script', 'style', 'svg'];
const DOCS_INDENT = "\t\t\t";

/**
 * The page list of tools/docs.json: key => [title, group], in order.
 * @return array{site: string, texts: array<string, string>, pages: array<string, array{string, string}>, twins: array<string, list<string>>}
 */
function DOCS__Config(): array
{
	$config = json_decode((string)file_get_contents(__DIR__ . '/docs.json'), true, 512, JSON_THROW_ON_ERROR);
	$pages = [];
	foreach ($config['groups'] as $group) {
		foreach ($group['pages'] as $key => $title) {
			$pages[$key] = [$title, $group['title']];
		}
	}
	return ['site' => $config['site'], 'texts' => $config['texts'], 'pages' => $pages, 'twins' => $config['twins']];
}

/** The text of an HTML fragment: tags gone, entities decoded, white space as single spaces. */
function DOCS__Plain(string $html): string
{
	return trim((string)preg_replace('~\s+~u', ' ', html_entity_decode(strip_tags($html), ENT_QUOTES | ENT_HTML5)));
}

/**
 * The source of the page $key, with what it breaks: an h1, a lead paragraph, every id beginning with "$key-".
 * @return array{html: string, title: string, lead: string, errors: list<string>}
 */
function DOCS__Source(string $key): array
{
	$file = 'docs/src/' . $key . '.html';
	$html = (string)@file_get_contents(DOCS_ROOT . '/' . $file);
	$errors = [];
	if ($html === '') {
		return ['html' => '', 'title' => '', 'lead' => '', 'errors' => [$file . ' is missing']];
	}
	$title = preg_match('~<h1>(.*?)</h1>~s', $html, $m) === 1 ? DOCS__Plain($m[1]) : '';
	$lead = preg_match('~<p class="docs-lead">(.*?)</p>~s', $html, $m) === 1 ? DOCS__Plain($m[1]) : '';
	if ($title === '' || $lead === '') {
		$errors[] = $file . ' needs an <h1> and a <p class="docs-lead">';
	}
	preg_match_all('~\sid="([^"]+)"~', (string)preg_replace('~<pre\b.*?</pre>~s', '', $html), $ids);
	foreach ($ids[1] as $id) {
		if (!str_starts_with($id, $key . '-')) {
			$errors[] = $file . ': the id "' . $id . '" must begin with "' . $key . '-", so that it stays unique on the all-components page';
		}
	}
	return ['html' => $html, 'title' => $title, 'lead' => $lead, 'errors' => $errors];
}

/** The offset of the </div> that closes the div whose content begins at $from. */
function DOCS__BlockEnd(string $html, int $from): int
{
	$depth = 1;
	preg_match_all('~<div\b|</div>~', $html, $tags, PREG_OFFSET_CAPTURE, $from);
	foreach ($tags[0] as [$tag, $at]) {
		$depth += $tag === '</div>' ? -1 : 1;
		if ($depth === 0) {
			return $at;
		}
	}
	throw new RuntimeException('a div is not closed after offset ' . $from);
}

/**
 * The blocks of the class $class in the source, in order: [the block's start, its end after </div>, its inner markup,
 * the indent of its line].
 * @return list<array{int, int, string, string}>
 */
function DOCS__Blocks(string $html, string $class): array
{
	preg_match_all('~<div class="' . preg_quote($class, '~') . '(?: [^"]*)?"[^>]*>~', $html, $found, PREG_OFFSET_CAPTURE);
	$blocks = [];
	foreach ($found[0] as [$tag, $at]) {
		$inner = $at + strlen($tag);
		$end = DOCS__BlockEnd($html, $inner);
		$line = strrpos(substr($html, 0, $at), "\n");
		$blocks[] = [$at, $end + 6, substr($html, $inner, $end - $inner), substr($html, $line === false ? 0 : $line + 1, $at - ($line === false ? 0 : $line + 1))];
	}
	return $blocks;
}

/** The markup as the reader sees it: the edge blank lines gone, the common indent removed, escaped. */
function DOCS__Code(string $markup): string
{
	$lines = explode("\n", rtrim($markup));
	while ($lines !== [] && trim($lines[0]) === '') {
		array_shift($lines);
	}
	$filled = array_filter($lines, fn(string $line): bool => trim($line) !== '');
	$indent = $filled === [] ? 0 : min(array_map(fn(string $line): int => strlen($line) - strlen(ltrim($line, "\t")), $filled));
	$lines = array_map(fn(string $line): string => trim($line) === '' ? '' : substr($line, $indent), $lines);
	return htmlspecialchars(implode("\n", $lines), ENT_NOQUOTES | ENT_HTML5);
}

/** The source with the code of each example printed right after it, the two joined in a sample. */
function DOCS__WithCode(string $html): string
{
	$out = '';
	$last = 0;
	foreach (DOCS__Blocks($html, 'docs-example') as [$start, $end, $markup, $indent]) {
		$out .= substr($html, $last, $start - $last) . '<div class="docs-sample">' . substr($html, $start, $end - $start) . "\n" . $indent . '<pre class="docs-code" tabindex="0"><code>' . DOCS__Code($markup) . '</code></pre></div>';
		$last = $end;
	}
	return $out . substr($html, $last);
}

/** The side navigation: the groups and their pages, the current one marked. */
function DOCS__Nav(array $config, string $current): string
{
	$out = '';
	$group = '';
	foreach ([...$config['pages'], 'all' => ['All components', 'Reference']] as $key => [$title, $in]) {
		if ($in !== $group) {
			$out .= DOCS_INDENT . '<div class="app-section">' . $in . "</div>\n";
			$group = $in;
		}
		$out .= DOCS_INDENT . '<a class="app-link" href="' . $key . '.html"' . ($key === $current ? ' aria-current="page"' : '') . '>' . htmlspecialchars($title) . "</a>\n";
	}
	return $out . DOCS_INDENT . '<a class="app-link" href="../reference/demo/list.html">Demo screens</a>' . "\n" . DOCS_INDENT . '<a class="app-link" href="../checks/">Checks in real engines</a>' . "\n";
}

/** The custom properties of a stylesheet: [declared, read and not declared], each in order of appearance. */
function DOCS__Properties(string $css): array
{
	preg_match_all('~(--redz-[a-z0-9-]+)\s*:~', $css, $declared);
	preg_match_all('~var\((--redz-[a-z0-9-]+)~', $css, $read);
	$own = array_values(array_unique($declared[1]));
	return [$own, array_values(array_diff(array_unique($read[1]), $own))];
}

/** The section of the tokens the component $key declares and reads; '' when it has no stylesheet of its own. */
function DOCS__TokensSection(string $key): string
{
	$file = 'css/components/' . $key . '.css';
	if (!is_file(DOCS_ROOT . '/' . $file)) {
		return '';
	}
	[$own, $read] = DOCS__Properties((string)file_get_contents(DOCS_ROOT . '/' . $file));
	$list = fn(array $names): string => implode(', ', array_map(fn(string $name): string => '<code>' . $name . '</code>', $names));
	$out = "\n\t\t<section class=\"vstack gap-12\" aria-labelledby=\"" . $key . "-tokens\">\n\t\t\t<h2 id=\"" . $key . "-tokens\">Tokens</h2>\n";
	$out .= "\t\t\t<p>From <a href=\"https://github.com/redz-tech/REDZ.UI/blob/main/" . $file . '"><code>' . $file . '</code></a>' . ($own === [] ? ', which declares no custom property of its own.' : '. It declares ' . $list($own) . ' on its root, never on rows or items.') . "</p>\n";
	if ($read !== []) {
		$out .= "\t\t\t<p>It reads the theme's " . $list($read) . ".</p>\n";
	}
	return $out . "\t\t</section>\n";
}

/**
 * The rows of the Bootstrap 5.3 map that change something, breakpoint forms left to their rule: a list of [bs5, redz,
 * kind, scope, page, note], or [] before the map exists.
 * @return list<list<string>>
 */
function DOCS__MapRows(): array
{
	$file = DOCS_ROOT . '/' . DOCS_MAP;
	if (!is_file($file)) {
		return [];
	}
	$rows = [];
	foreach (array_slice(explode("\n", trim((string)file_get_contents($file))), 1) as $line) {
		$row = array_pad(explode("\t", $line), 6, '');
		if ($row[2] !== 'same' && preg_match('~-(sm|md|lg|xl|xxl|print)(-|$)~', $row[0]) !== 1) {
			$rows[] = $row;
		}
	}
	return $rows;
}

/** A table of map rows. */
function DOCS__MapTable(array $rows): string
{
	$out = "\t\t\t<table class=\"table docs-table\">\n\t\t\t\t<thead><tr><th scope=\"col\">Bootstrap 5.3</th><th scope=\"col\">REDZ.UI</th><th scope=\"col\">Change</th><th scope=\"col\">Note</th></tr></thead>\n\t\t\t\t<tbody>\n";
	foreach ($rows as [$bs5, $redz, $kind, , , $note]) {
		$out .= "\t\t\t\t\t<tr><td><code>" . htmlspecialchars($bs5) . '</code></td><td>' . ($redz === '' ? '—' : '<code>' . htmlspecialchars($redz) . '</code>') . '</td><td>' . htmlspecialchars($kind) . '</td><td>' . htmlspecialchars($note) . "</td></tr>\n";
	}
	return $out . "\t\t\t\t</tbody>\n\t\t\t</table>\n";
}

/** The section of the map rows of the page $key; '' when the map has none for it. */
function DOCS__MapSection(string $key, array $rows): string
{
	$mine = array_values(array_filter($rows, fn(array $row): bool => $row[4] === $key));
	if ($mine === []) {
		return '';
	}
	return "\n\t\t<section class=\"vstack gap-12\" aria-labelledby=\"" . $key . "-from-bootstrap\">\n\t\t\t<h2 id=\"" . $key . "-from-bootstrap\">From Bootstrap 5.3</h2>\n" . DOCS__MapTable($mine) . "\t\t</section>\n";
}

